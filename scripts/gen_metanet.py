#!/usr/bin/env python3
"""Writes src/scoring/MetaNetWeights.sol from model/model.json and
test/scoring/MetaNetVectors.sol with (status, bodyBytes, latencyMs) -> numpy score for the parity test.
Vectors: every distinct (status, bytes, latency) of the time-split test rows in model/data/delivery.csv.gz
(capped) plus hand-picked edge cases."""
import json, os, random, sys
HERE = os.path.dirname(os.path.abspath(__file__)); REPO = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(REPO, "model"))
import numpy as np
from features import featurize, forward, score, load, time_split

m = json.load(open(os.path.join(REPO, "model", "model.json")))
S = 10**18
q = lambda x: int(round(x * S))
w1 = [[q(m["W1"][i][j]) for j in range(8)] for i in range(10)]
lines = ["// SPDX-License-Identifier: MIT", "// GENERATED by scripts/gen_metanet.py from model/model.json. Do not edit.", "pragma solidity ^0.8.29;", "",
         "library MetaNetWeights {", "    int256 internal constant S = 1e18;"]
lines.append("    function all() internal pure returns (int256[80] memory w1, int256[8] memory b1, int256[8] memory w2) {")
lines.append("        w1 = [" + ", ".join(f"int256({w1[i][j]})" for i in range(10) for j in range(8)) + "];")
lines.append("        b1 = [" + ", ".join(f"int256({q(v)})" for v in m["b1"]) + "];")
lines.append("        w2 = [" + ", ".join(f"int256({q(r[0])})" for r in m["W2"]) + "];")
lines.append("    }")
lines.append(f"    int256 internal constant B2 = {q(m['b2'][0])};")
lines.append("}")
open(os.path.join(REPO, "src", "scoring", "MetaNetWeights.sol"), "w").write("\n".join(lines) + "\n")

rows, X, y = load()
cut, _, _ = time_split(rows)
seen, vec = set(), []
def add(st, nb, lat):
    k = (st, nb, lat)
    if k in seen: return
    seen.add(k)
    x = featurize(None if st == 0 else st, None if st == 0 else nb, None, None if st == 0 else lat)
    vec.append((st, nb, lat, int(score(forward(m, np.array([x])))[0])))
for st, nb, lat in [(200, 0, 500), (200, 1, 500), (200, 1500, 800), (202, 50, 300), (301, 0, 100), (404, 30, 200),
                    (500, 100, 1000), (0, 0, 0), (200, 10**7, 120000), (200, 2, 0), (402, 1200, 90)]:
    add(st, nb, lat)
random.seed(7)
test = rows[cut:]
random.shuffle(test)
neg = [r for r in test if r["delivery"] != "delivered"]
pos = [r for r in test if r["delivery"] == "delivered"]
for r in neg[:400] + pos:
    if len(vec) >= 500: break
    if r["http_status_paid"] in ("", None) or r["body_bytes"] in ("", None) or r["latency_ms"] in ("", None): continue
    add(int(r["http_status_paid"]), int(r["body_bytes"]), int(r["latency_ms"]))
out = ["// SPDX-License-Identifier: MIT", "// GENERATED by scripts/gen_metanet.py. (status, bodyBytes, latencyMs, numpy score). status 0 = no response.",
       "pragma solidity ^0.8.29;", "", "library MetaNetVectors {",
       f"    uint256 internal constant N = {len(vec)};",
       f"    function all() internal pure returns (uint256[{len(vec)*4}] memory v) {{",
       "        v = [" + ", ".join(f"uint256({a})" for t in vec for a in t) + "];", "    }", "}"]
open(os.path.join(REPO, "test", "scoring", "MetaNetVectors.sol"), "w").write("\n".join(out) + "\n")
print("weights written; vectors", len(vec), "positives(>=70)", sum(1 for t in vec if t[3] >= 70))
